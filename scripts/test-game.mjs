import assert from 'node:assert/strict';
import {game} from './load-game.mjs';
const {createMission,applyPlayer,playerView}=game;
const m=createMission('Test','9876543210',10,60,false),t=m.teams[0];
assert.equal(m.qr.length,3);
assert.ok(applyPlayer(m,t,'scan',{token:m.qr[0]}).error);
m.phase='games';m.startedAt=Date.now();
assert.ok(applyPlayer(m,t,'scan',{token:m.qr[0]}).error);
m.phase='hunt';
assert.equal(t.solved.length,0);
assert.ok(applyPlayer(m,t,'answer',{index:0,answer:'map'}).error,'Games must stop after the alert');
for(const token of m.qr)assert.ok(!applyPlayer(m,t,'scan',{token}).error);
const clues=playerView(m,t).clues;
assert.deepEqual(clues.map(c=>c.digits),['654','987','3210']);
assert.deepEqual(clues.map(c=>c.digits.length),[3,3,4]);
assert.equal(playerView(m,t).phone,undefined);
const result=applyPlayer(m,t,'decode',{number:m.phone},Date.now()+4000);
assert.ok(!result.error);
assert.equal(playerView(m,t).phone,m.phone,'Unfinished mini games must not block decoding after alert');
assert.equal(m.winner,null);
assert.equal(playerView(m,m.teams[1]).clues.length,0);
console.log('PASS: BLACKOUT interrupts unfinished games; 3 QR clues split 3+3+4; number verifies without completing games; teams stay isolated.');
const custom=createMission('Custom','9876543210',2,60,true);
custom.puzzles=[{title:'Custom',type:'RIDDLE',question:'Name our event',hint:'Eight letters',answer:'blackout'},{title:'Count',type:'LOGIC',question:'2+2?',hint:'Add them',answer:'4'}];
custom.phase='games';custom.startedAt=Date.now();
custom.miniGameMode='puzzles';
applyPlayer(custom,custom.teams[0],'answer',{index:0,answer:'BLACKOUT'},Date.now()+4000);
assert.deepEqual(custom.teams[0].solved,[0]);
assert.equal(playerView(custom,custom.teams[0]).puzzles[0].question,'Name our event');
assert.equal(playerView(custom,custom.teams[0]).puzzles[0].answer,undefined);
assert.equal(playerView(custom,custom.teams[0]).puzzles[0].hint,undefined);
console.log('PASS: custom questions, server answer checks and answer/hint secrecy.');
