import assert from 'node:assert/strict';
import {game,sea} from './load-game.mjs';
const {createMission,applyPlayer,playerView}=game;
const {validFleet,randomFleet}=sea;
const fleet=[[0,1,2,3,4],[10,11,12,13],[20,21,22],[30,31,32],[40,41]];
assert.equal(validFleet(fleet),true);
assert.equal(validFleet([[8,9,10,11,12],...fleet.slice(1)]),false,'Row wrapping must be rejected');
assert.equal(validFleet([fleet[0],[0,1,2,3],...fleet.slice(2)]),false,'Overlapping ships must be rejected');
assert.equal(validFleet([[0,0,1,2,3],...fleet.slice(1)]),false);
assert.equal(validFleet([[0,1,2,3,100],...fleet.slice(1)]),false);
for(let i=0;i<200;i++)assert.equal(validFleet(randomFleet()),true);
const m=createMission('Naval rehearsal','9876543210',8,60,true);
assert.equal(m.miniGameMode,'sea-battle');assert.equal(m.seaBattles.length,4);
assert.equal(new Set(m.seaBattles.flatMap(g=>g.teams)).size,8);
const [a,b,c]=m.teams;
assert.ok(applyPlayer(m,a,'sea-deploy',{fleet}).error,'Lobby must reject deployment');
m.phase='games';m.startedAt=Date.now();
assert.ok(applyPlayer(m,a,'sea-deploy',{fleet:[]}).error);
assert.ok(!applyPlayer(m,a,'sea-deploy',{fleet}).error);
assert.ok(applyPlayer(m,a,'sea-deploy',{fleet}).error,'Locked fleet cannot move');
assert.ok(applyPlayer(m,a,'sea-fire',{cell:0}).error,'Both fleets must be ready');
assert.ok(!applyPlayer(m,b,'sea-deploy',{fleet}).error);
const g=m.seaBattles[0];g.turn=a.id;
const view=playerView(m,a);
assert.deepEqual(view.seaBattle.ownFleet,fleet);
assert.equal(view.seaBattle.fleets,undefined);assert.equal(view.seaBattles,undefined);
assert.equal(view.seaBattle.opponentFleet,undefined,'Opponent layout must never reach a player');
assert.equal(playerView(m,c).seaBattle.shots.length,0);
assert.ok(applyPlayer(m,b,'sea-fire',{cell:0}).error,'Wrong turn must fail');
for(const cell of [-1,100,1.2,'0',null])assert.ok(applyPlayer(m,a,'sea-fire',{cell}).error);
assert.ok(!applyPlayer(m,a,'sea-fire',{cell:0,hit:false}).error);
assert.equal(g.shots[0].hit,true,'The server calculates hits');assert.equal(g.turn,b.id,'Hits also pass the turn');
assert.ok(applyPlayer(m,a,'sea-fire',{cell:1}).error);
assert.ok(!applyPlayer(m,b,'sea-fire',{cell:99}).error);
assert.ok(applyPlayer(m,a,'sea-fire',{cell:0}).error,'Duplicate shots must fail');
m.pausedAt=Date.now();assert.ok(applyPlayer(m,a,'sea-fire',{cell:1}).error);m.pausedAt=null;
m.phase='hunt';assert.ok(applyPlayer(m,a,'sea-fire',{cell:1}).error,'BLACKOUT must stop battles');m.phase='games';
const remaining=fleet.flat().filter(c=>c!==0);let miss=98;
for(const cell of remaining){assert.ok(!applyPlayer(m,a,'sea-fire',{cell}).error);if(!g.winner){assert.ok(!applyPlayer(m,b,'sea-fire',{cell:miss--}).error);}}
assert.equal(g.winner,a.id);assert.equal(g.shots.filter(s=>s.by===a.id&&s.sunk).length,5);
assert.equal(playerView(m,a).seaBattle.opponentRemaining,0);
assert.equal(playerView(m,b).seaBattle.remaining,0);
assert.equal(m.winner,null,'Naval result must not declare the winning phone call');
assert.ok(applyPlayer(m,b,'sea-fire',{cell:60}).error,'Finished battles reject attacks');
assert.equal(playerView(m,c).seaBattle.started,false,'Other duels remain isolated');
const restored=JSON.parse(JSON.stringify(m));assert.equal(playerView(restored,restored.teams[0]).seaBattle.won,true);
console.log('PASS: fleet validation, random layouts, 8-team pairing, hidden fleets, alternating turns after hits, duplicate/range checks, pause/BLACKOUT gates, sunk ships, victory, persistence and independent duels.');
